// Helper to expand and enrich records with derived columns
export const enrichRecord = (record: any): SalesRecord => {
  const d = new Date(record.orderDate || '2024-01-01');
  const year = isNaN(d.getFullYear()) ? 2024 : d.getFullYear();
  const monthIdx = isNaN(d.getMonth()) ? 0 : d.getMonth();
  const quarterMonth = Math.floor(monthIdx / 3) + 1;
  const quarter = `Q${quarterMonth} ${year}`;
  
  const monthNames = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  const month = `${monthNames[monthIdx]} ${year}`;

  const sales = Number(record.sales) || (Number(record.quantity || 1) * Number(record.unitPrice || 0) * (1 - (Number(record.discount) || 0)));
  const cost = Number(record.cogs !== undefined ? record.cogs : (record.cost !== undefined ? record.cost : (sales * 0.52)));
  const grossProfit = Number(record.grossProfit !== undefined ? record.grossProfit : (sales - cost));
  
  // Operating Expenses (OPEX: SG&A, distribution, sales commissions, operational overhead)
  const explicitOpex = record.operatingExpenses !== undefined ? Number(record.operatingExpenses) :
                       (record.opex !== undefined ? Number(record.opex) :
                       (record.expenses !== undefined ? Number(record.expenses) : undefined));
  const operatingExpenses = explicitOpex !== undefined && !isNaN(explicitOpex)
    ? explicitOpex
    : Math.max(0, sales * 0.16);

  const netProfit = Number(record.netProfit !== undefined ? record.netProfit : (grossProfit - operatingExpenses));
  const profit = netProfit;
  const profitMargin = sales > 0 ? (grossProfit / sales) * 100 : 0;

  return {
    ...record,
    orderId: String(record.orderId || `ORD-${Math.random().toString(36).substring(2, 7).toUpperCase()}`),
    orderDate: String(record.orderDate || '2024-01-01'),
    year,
    quarter,
    month,
    monthIndex: monthIdx,
    customerName: String(record.customerName || 'Anonymous Client'),
    customerSegment: String(record.customerSegment || 'Enterprise'),
    region: String(record.region || 'North America'),
    country: String(record.country || 'United States'),
    category: String(record.category || 'General Sales'),
    subCategory: String(record.subCategory || 'Standard'),
    productName: String(record.productName || 'Standard Product'),
    salesRep: String(record.salesRep || 'Direct Sales'),
    quantity: Number(record.quantity) || 1,
    unitPrice: Number(record.unitPrice) || sales,
    discount: Number(record.discount) || 0,
    sales: Math.round(sales * 100) / 100,
    cost: Math.round(cost * 100) / 100,
    cogs: Math.round(cost * 100) / 100,
    grossProfit: Math.round(grossProfit * 100) / 100,
    operatingExpenses: Math.round(operatingExpenses * 100) / 100,
    netProfit: Math.round(netProfit * 100) / 100,
    profit: Math.round(profit * 100) / 100,
    profitMargin: Math.round(profitMargin * 10) / 10,
    paymentMethod: String(record.paymentMethod || 'Credit Card'),
    orderStatus: (record.orderStatus as any) || 'Completed'
  };
};

export const DEFAULT_SALES_DATA: SalesRecord[] = RAW_SALES_RECORDS.map(enrichRecord);

// Generate formatted CSV representation of the dataset for copy / export
export const generateSalesCsv = (records: SalesRecord[]): string => {
  const headers = [
    'Order ID',
    'Order Date',
    'Customer Name',
    'Customer Segment',
    'Region',
    'Country',
    'Category',
    'Sub-Category',
    'Product Name',
    'Sales Rep',
    'Quantity',
    'Unit Price',
    'Discount',
    'Sales',
    'Cost',
    'Profit',
    'Profit Margin %',
    'Payment Method',
    'Order Status'
  ];

  const rows = records.map(r => [
    `"${r.orderId}"`,
    `"${r.orderDate}"`,
    `"${r.customerName.replace(/"/g, '""')}"`,
    `"${r.customerSegment}"`,
    `"${r.region}"`,
    `"${r.country}"`,
    `"${r.category}"`,
    `"${r.subCategory}"`,
    `"${r.productName.replace(/"/g, '""')}"`,
    `"${r.salesRep}"`,
    r.quantity,
    r.unitPrice,
    r.discount,
    r.sales,
    r.cost,
    r.profit,
    r.profitMargin,
    `"${r.paymentMethod}"`,
    `"${r.orderStatus}"`
  ]);

  return [headers.join(','), ...rows.map(r => r.join(','))].join('\n');
};

export const DEFAULT_SALES_CSV_STRING = generateSalesCsv(DEFAULT_SALES_DATA);
